def compose_morning_brief(
    profiles: ProfileRepository,
    tasks: TaskRepository,
    prospects: ProspectRepository | None = None,
    crm: CrmRepository | None = None,
    meetings: MeetingRepository | None = None,
    preferences: ReportPreferences | None = None,
    today: date | None = None,
) -> dict[str, Any]:
    reference = today or date.today()
    prefs = preferences or ReportPreferences((), ())
    business = profiles.get_business()

    buckets: dict[str, list[dict[str, Any]]] = {
        "en_retard": [], "aujourdhui": [], "a_venir": [], "sans_echeance": [],
    }
    for task in tasks.list_open():
        buckets[task.bucket(reference)].append(
            {"task_id": task.task_id, "title": task.title, "due_date": task.due_date}
        )

    brief: dict[str, Any] = {
        "date": reference.isoformat(),
        "kind": "morning",
        "address_as": business.address_as(),
        "company_name": business.company_name,
        "goals": business.goals,
        "open_task_count": sum(len(items) for items in buckets.values()),
        "tasks": buckets,
    }
    if prefs.morning_enabled("priorites") and business.current_priorities:
        brief["priorities"] = business.current_priorities

    # Legacy pipeline (kept until every prospect is migrated into the CRM).
    if prospects is not None:
        brief["due_follow_ups"] = [
            {
                "prospect_id": p.prospect_id, "name": p.name, "company": p.company,
                "stage": p.stage, "next_action": p.next_action,
                "next_action_date": p.next_action_date,
            }
            for p in prospects.due_follow_ups(reference)
        ]

    if meetings is not None and prefs.morning_enabled("actions_reunions"):
        brief["meeting_actions"] = meetings.open_actions(limit=10)

    risks: list[str] = []
    opportunities: list[dict[str, Any]] = []
    if crm is not None:
        overview = crm.overview(reference)
        if prefs.morning_enabled("relances"):
            brief["follow_ups"] = overview["follow_ups"]
        if prefs.morning_enabled("devis"):
            brief["awaiting_deals"] = overview["awaiting_deals"]
        if prefs.morning_enabled("contrats"):
            brief["expiring_contracts"] = overview["expiring_contracts"]
        if prefs.morning_enabled("projets"):
            brief["blocked_projects"] = overview["blocked_projects"]
        brief["counts"] = overview["counts"]

        for project in overview["blocked_projects"]:
            reason = project.get("blocker") or ("échéance dépassée" if project.get("late") else "santé critique")
            risks.append(f"Projet « {project['name']} » : {reason}")
        for contract in overview["expiring_contracts"]:
            remaining = contract.get("days_to_expiry")
            if remaining is not None and remaining <= 30:
                risks.append(
                    f"Contrat « {contract['title']} » expire dans {remaining} jour(s)"
                )
        for deal in crm.list_deals():
            if deal.stage in ("brouillon", "envoyé", "relancé") and deal.amount:
                opportunities.append(
                    {
                        "deal_id": deal.deal_id, "title": deal.title,
                        "amount": deal.amount, "currency": deal.currency, "stage": deal.stage,
                    }
                )

    if buckets["en_retard"]:
        risks.append(f"{len(buckets['en_retard'])} tâche(s) en retard")
    if prefs.morning_enabled("risques"):
        brief["risks"] = risks
    if prefs.morning_enabled("opportunites"):
        brief["opportunities"] = opportunities
        brief["opportunity_total"] = round(sum(item["amount"] for item in opportunities), 2)
    if prefs.morning_enabled("recommandations"):
        brief["recommendations"] = _morning_recommendations(brief)
    return brief


def _morning_recommendations(brief: Mapping[str, Any]) -> list[str]:
    """Next-best actions, derived only from facts already in the brief."""
    recommendations: list[str] = []
    late = brief.get("tasks", {}).get("en_retard", [])
    if late:
        recommendations.append(f"Traiter d'abord « {late[0]['title']} », en retard.")
    for deal in brief.get("awaiting_deals", [])[:2]:
        waiting = deal.get("waiting_days")
        delay = f" (sans réponse depuis {waiting} jours)" if waiting else ""
        recommendations.append(f"Relancer le devis « {deal['title']} »{delay}.")
    for contact in brief.get("follow_ups", [])[:2]:
        recommendations.append(
            f"Reprendre contact avec {contact['name']} — {contact.get('silent_days', 0)} jours sans échange."
        )
    for project in brief.get("blocked_projects", [])[:2]:
        recommendations.append(
            f"Débloquer le projet « {project['name']} » : {project.get('blocker') or 'point de situation à faire'}."
        )
    for contract in brief.get("expiring_contracts", [])[:1]:
        recommendations.append(
            f"Décider du renouvellement du contrat « {contract['title']} »."
        )
    for action in brief.get("meeting_actions", [])[:1]:
        recommendations.append(
            f"Relancer {action['owner']} sur : {action['description']}."
        )
    return recommendations[:6]


def format_morning_text(brief: Mapping[str, Any]) -> str:
    """French plain-text rendering, for e-mail, voice and display."""
    lines = [f"Brief EMEFA du {brief.get('date', '')}"]
    if brief.get("company_name"):
        lines[0] += f" — {brief['company_name']}"
    if brief.get("priorities"):
        lines += ["", f"Priorités du jour : {brief['priorities']}"]

    task_buckets = brief.get("tasks", {})
    if brief.get("open_task_count"):
        lines += ["", f"Tâches ouvertes : {brief['open_task_count']}"]
        for key, title in _BUCKET_TITLES:
            for task in task_buckets.get(key, []):
                due = f" (échéance {task['due_date']})" if task.get("due_date") else ""
                lines.append(f"- [{title}] {task['title']}{due}")
    else:
        lines += ["", "Aucune tâche ouverte."]

    _append_list(
        lines, "Relances commerciales dues :", brief.get("due_follow_ups", []),
        lambda p: f"- {p['name']}"
                  + (f" ({p['company']})" if p.get("company") else "")
                  + (f" — {p['next_action']}" if p.get("next_action") else ""),
    )
    _append_list(
        lines, "Clients à relancer :", brief.get("follow_ups", []),
        lambda c: f"- {c['name']}"
                  + (f" ({c['company']})" if c.get("company") else "")
                  + f" — {c.get('silent_days', 0)} jours sans échange",
    )
    _append_list(
        lines, "Devis en attente de réponse :", brief.get("awaiting_deals", []),
        lambda d: f"- {d['title']}"
                  + (f" — {d['contact_name']}" if d.get("contact_name") else "")
                  + f" — {_money(d)}"
                  + (f" — {d['waiting_days']} jours" if d.get("waiting_days") else ""),
    )
    _append_list(
        lines, "Contrats à échéance :", brief.get("expiring_contracts", []),
        lambda c: f"- {c['title']}"
                  + (f" ({c['contact_name']})" if c.get("contact_name") else "")
                  + f" — expire dans {c.get('days_to_expiry')} jour(s)",
    )
    _append_list(
        lines, "Projets à surveiller :", brief.get("blocked_projects", []),
        lambda p: f"- {p['name']} [{p['status']}/{p['health']}]"
                  + (f" — {p['blocker']}" if p.get("blocker") else "")
                  + (" — échéance dépassée" if p.get("late") else ""),
    )
    _append_list(
        lines, "Actions attendues d'autres personnes :", brief.get("meeting_actions", []),
        lambda a: f"- {a['owner']} : {a['description']}"
                  + (f" (pour le {a['due_date']})" if a.get("due_date") else ""),
    )
    opportunities = brief.get("opportunities", [])
    if opportunities:
        total = brief.get("opportunity_total", 0)
        currency = opportunities[0].get("currency", "")
        lines += ["", f"Opportunités ouvertes : {len(opportunities)} — {total:,.0f} {currency}".replace(",", " ")]
        for item in opportunities[:5]:
            lines.append(f"- {item['title']} — {_money(item)} [{item['stage']}]")
    _append_list(lines, "Risques :", brief.get("risks", []), lambda item: f"- {item}")
    _append_list(
        lines, "Recommandations :", brief.get("recommendations", []), lambda item: f"- {item}"
    )
    if brief.get("goals"):
        lines += ["", f"Objectifs : {brief['goals']}"]
    return "\n".join(lines)


def _money(entry: Mapping[str, Any]) -> str:
    amount = entry.get("amount", entry.get("value", 0)) or 0
    return f"{amount:,.0f} {entry.get('currency', '')}".replace(",", " ").strip()


def _append_list(lines: list[str], title: str, items: Sequence[Any], render: Any) -> None:
    if not items:
        return
    lines += ["", title]
    lines += [render(item) for item in items]


