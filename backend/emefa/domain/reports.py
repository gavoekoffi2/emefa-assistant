def compose_evening_report(
    profiles: ProfileRepository,
    tasks: TaskRepository,
    crm: CrmRepository | None = None,
    meetings: MeetingRepository | None = None,
    preferences: ReportPreferences | None = None,
    today: date | None = None,
) -> dict[str, Any]:
    reference = today or date.today()
    prefs = preferences or ReportPreferences((), ())
    business = profiles.get_business()
    tomorrow = reference + timedelta(days=1)

    completed = [
        {"task_id": task.task_id, "title": task.title, "completed_at": task.completed_at}
        for task in tasks.list_completed_since(reference.isoformat())
    ]
    open_tasks = tasks.list_open()
    remaining = [
        {
            "task_id": task.task_id, "title": task.title,
            "due_date": task.due_date, "bucket": task.bucket(reference),
        }
        for task in open_tasks
    ]
    late = [item for item in remaining if item["bucket"] == "en_retard"]
    due_today = [item for item in remaining if item["bucket"] == "aujourdhui"]

    report: dict[str, Any] = {
        "date": reference.isoformat(),
        "kind": "evening",
        "address_as": business.address_as(),
        "company_name": business.company_name,
        "completed_count": len(completed),
        "remaining_count": len(remaining),
    }
    if prefs.evening_enabled("termine"):
        report["completed"] = completed
    if prefs.evening_enabled("restant"):
        report["remaining"] = remaining[:12]

    blockers: list[str] = []
    if crm is not None:
        for project in crm.blocked_projects(reference):
            blockers.append(
                f"Projet « {project['name']} » : "
                f"{project.get('blocker') or ('échéance dépassée' if project.get('late') else 'santé critique')}"
            )
    if late:
        blockers.append(f"{len(late)} tâche(s) toujours en retard")
    if meetings is not None:
        overdue_actions = [
            action for action in meetings.open_actions(limit=20)
            if action.get("due_date") and action["due_date"] < reference.isoformat()
        ]
        if overdue_actions:
            blockers.append(
                f"{len(overdue_actions)} action(s) de réunion en retard chez d'autres personnes"
            )
    if prefs.evening_enabled("blocages"):
        report["blockers"] = blockers

    tomorrow_items: list[str] = []
    tomorrow_items += [f"Rattraper : {item['title']}" for item in late[:3]]
    tomorrow_items += [f"Terminer : {item['title']}" for item in due_today[:3]]
    tomorrow_items += [
        f"Échéance demain : {item['title']}"
        for item in remaining
        if item.get("due_date") == tomorrow.isoformat()
    ][:3]
    if crm is not None:
        for deal in crm.awaiting_deals(reference)[:2]:
            tomorrow_items.append(f"Relancer le devis « {deal['title']} »")
        for contact in crm.follow_ups(reference)[:2]:
            tomorrow_items.append(f"Reprendre contact avec {contact['name']}")
    if business.current_priorities and not tomorrow_items:
        tomorrow_items.append(f"Avancer sur : {business.current_priorities}")
    if prefs.evening_enabled("demain"):
        report["tomorrow"] = tomorrow_items[:6]

    if prefs.evening_enabled("recommandations"):
        recommendations: list[str] = []
        if late:
            recommendations.append(
                "Replanifier ou déléguer les tâches en retard plutôt que de les reporter à nouveau."
            )
        if len(completed) == 0 and remaining:
            recommendations.append(
                "Aucune tâche clôturée aujourd'hui : isoler une seule priorité pour demain."
            )
        if blockers:
            recommendations.append("Traiter en priorité le premier blocage listé ci-dessus.")
        report["recommendations"] = recommendations
    if prefs.evening_enabled("resume"):
        report["summary"] = (
            f"{len(completed)} tâche(s) terminée(s), {len(remaining)} en cours, "
            f"{len(blockers)} blocage(s) identifié(s)."
        )
    return report


def format_evening_text(report: Mapping[str, Any]) -> str:
    lines = [f"Rapport du soir EMEFA — {report.get('date', '')}"]
    if report.get("company_name"):
        lines[0] += f" — {report['company_name']}"
    if report.get("summary"):
        lines += ["", report["summary"]]
    _append_list(
        lines, "Terminé aujourd'hui :", report.get("completed", []),
        lambda item: f"- {item['title']}",
    )
    if not report.get("completed") and "completed" in report:
        lines += ["", "Aucune tâche clôturée aujourd'hui."]
    _append_list(
        lines, "Reste à faire :", report.get("remaining", []),
        lambda item: f"- [{item['bucket']}] {item['title']}"
                     + (f" (échéance {item['due_date']})" if item.get("due_date") else ""),
    )
    _append_list(lines, "Blocages :", report.get("blockers", []), lambda item: f"- {item}")
    _append_list(
        lines, "Recommandations :", report.get("recommendations", []), lambda item: f"- {item}"
    )
    _append_list(
        lines, "Priorités de demain :", report.get("tomorrow", []), lambda item: f"- {item}"
    )
    return "\n".join(lines)
