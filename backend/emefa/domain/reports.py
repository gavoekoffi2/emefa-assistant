"""Executive briefings: the morning brief and the evening report.

Both are **deterministic**. Everything an executive is told here — a late
task, a silent client, an unanswered quotation, an expiring contract — is read
from the database, never generated by a model. That is what makes the brief
trustworthy enough to act on before coffee (CLAUDE.md §25, §33).

Sections are individually selectable so each executive gets the report they
actually read; an empty preference means "everything".
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path
from typing import Any

from emefa.domain import storage
from emefa.domain.crm import CrmRepository
from emefa.domain.meetings import MeetingRepository
from emefa.domain.profiles import ProfileRepository
from emefa.domain.prospects import ProspectRepository
from emefa.domain.storage import DEFAULT_USER_ID
from emefa.domain.tasks import TaskRepository

MORNING_SECTIONS: tuple[tuple[str, str], ...] = (
    ("priorites", "Priorités du jour"),
    ("taches", "Tâches"),
    ("actions_reunions", "Actions issues des réunions"),
    ("relances", "Clients à relancer"),
    ("devis", "Devis en attente de réponse"),
    ("contrats", "Contrats à échéance"),
    ("projets", "Projets à surveiller"),
    ("opportunites", "Opportunités"),
    ("risques", "Risques"),
    ("recommandations", "Recommandations"),
)
EVENING_SECTIONS: tuple[tuple[str, str], ...] = (
    ("resume", "Résumé de la journée"),
    ("termine", "Terminé aujourd'hui"),
    ("restant", "Reste à faire"),
    ("blocages", "Blocages"),
    ("recommandations", "Recommandations"),
    ("demain", "Priorités de demain"),
)

_BUCKET_TITLES = (
    ("en_retard", "En retard"),
    ("aujourdhui", "Aujourd'hui"),
    ("a_venir", "À venir"),
    ("sans_echeance", "Sans échéance"),
)


@dataclass(frozen=True, slots=True)
class ReportPreferences:
    morning_sections: tuple[str, ...]
    evening_sections: tuple[str, ...]

    def morning_enabled(self, key: str) -> bool:
        return not self.morning_sections or key in self.morning_sections

    def evening_enabled(self, key: str) -> bool:
        return not self.evening_sections or key in self.evening_sections


class ReportPreferencesRepository:
    def __init__(self, database_path: Path) -> None:
        self.database_path = Path(database_path)
        storage.run_migrations(self.database_path)

    def get(self) -> ReportPreferences:
        with storage.connect(self.database_path) as connection:
            row = connection.execute(
                "SELECT morning_sections, evening_sections FROM report_preferences "
                "WHERE user_id = ?",
                (DEFAULT_USER_ID,),
            ).fetchone()
            if row is None:
                connection.execute(
                    "INSERT INTO report_preferences (user_id) VALUES (?)", (DEFAULT_USER_ID,)
                )
                return ReportPreferences((), ())
        return ReportPreferences(
            morning_sections=_split(row["morning_sections"]),
            evening_sections=_split(row["evening_sections"]),
        )

    def update(
        self,
        morning_sections: Sequence[str] | None = None,
        evening_sections: Sequence[str] | None = None,
    ) -> ReportPreferences:
        values: dict[str, str] = {}
        if morning_sections is not None:
            values["morning_sections"] = _join(morning_sections, MORNING_SECTIONS)
        if evening_sections is not None:
            values["evening_sections"] = _join(evening_sections, EVENING_SECTIONS)
        if values:
            assignments = ", ".join(f"{column} = ?" for column in values)
            with storage.connect(self.database_path) as connection:
                connection.execute(
                    f"UPDATE report_preferences SET {assignments}, "
                    "updated_at = CURRENT_TIMESTAMP WHERE user_id = ?",
                    (*values.values(), DEFAULT_USER_ID),
                )
        return self.get()


def _split(raw: str | None) -> tuple[str, ...]:
    return tuple(item for item in (raw or "").split(",") if item)


def _join(sections: Sequence[str], allowed: tuple[tuple[str, str], ...]) -> str:
    keys = {key for key, _ in allowed}
    return ",".join(sorted({str(item) for item in sections if item in keys}))


